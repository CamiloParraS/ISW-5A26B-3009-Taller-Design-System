      const orig = new Map(),
        $ = (s) => document.querySelector(s),
        $$ = (s) => [...document.querySelectorAll(s)];
      let lang = "es",
        cur = 0;
      const frames = $$(".frame");
      const meta = frames.map((f) => {
        let e = f.closest(".row"),
          note = "",
          h = "";
        while ((e = e.previousElementSibling)) {
          if (!note && e.matches("p.note")) note = e;
          if (e.matches("h2")) {
            h = e;
            break;
          }
        }
        return { f, h, note };
      });
      function translate() {
        const w = document.createTreeWalker(
          document.body,
          NodeFilter.SHOW_TEXT,
        );
        const ns = [];
        let n;
        while ((n = w.nextNode())) ns.push(n);
        ns.forEach((n) => {
          const p = n.parentElement;
          if (!p || p.closest("script,style,#nav,#capText,#count")) return;
          if (!orig.has(n)) orig.set(n, n.nodeValue);
          const o = orig.get(n),
            k = o.replace(/\s+/g, " ").trim();
          n.nodeValue =
            lang === "es" && ES[k]
              ? o.match(/^\s*/)[0] + ES[k] + o.match(/\s*$/)[0]
              : o;
        });
        document.documentElement.lang = lang;
      }
      function buildNav() {
        let g = null,
          html = "";
        meta.forEach((m, i) => {
          if (m.h !== g) {
            g = m.h;
            html += "<h4>" + g.textContent + "</h4>";
          }
          const l = m.f.querySelector(".lbl"),
            t = l.childNodes[0].textContent.trim(),
            s = l.querySelector("em")?.textContent || "";
          html += `<a data-i="${i}" class="${i === cur ? "on" : ""}">${t}${s ? "<small>" + s + "</small>" : ""}</a>`;
        });
        $("#nav").innerHTML = html;
      }
      function fit() {
        const f = frames[cur];
        f.style.zoom = 1;
        const r = $(".page").getBoundingClientRect();
        f.style.zoom = Math.min(
          (r.width - 64) / f.offsetWidth,
          (r.height - 48) / f.offsetHeight,
          1.3,
        );
      }
      function show(i) {
        cur = (i + frames.length) % frames.length;
        frames.forEach((f, j) => f.classList.toggle("active", j === cur));
        $$("#nav a").forEach((a) =>
          a.classList.toggle("on", +a.dataset.i === cur),
        );
        $("#nav a.on")?.scrollIntoView({ block: "nearest" });
        $("#capText").textContent = meta[cur].note.textContent;
        $("#count").textContent = cur + 1 + " / " + frames.length;
        history.replaceState(null, "", "#" + cur);
        fit();
      }
      function seg(id, k, v) {
        $$(id + " button").forEach((b) =>
          b.classList.toggle("on", b.dataset[k] === v),
        );
      }
      function setLang(l) {
        lang = l;
        translate();
        buildNav();
        show(cur);
        seg("#segLang", "l", l);
      }
      function setTheme(t) {
        document.documentElement.dataset.theme = t;
        seg("#segTheme", "t", t);
      }
      $("#nav").onclick = (e) => {
        const a = e.target.closest("a");
        if (a) show(+a.dataset.i);
      };
      $("#prev").onclick = () => show(cur - 1);
      $("#next").onclick = () => show(cur + 1);
      $("#segLang").onclick = (e) =>
        e.target.dataset.l && setLang(e.target.dataset.l);
      $("#segTheme").onclick = (e) =>
        e.target.dataset.t && setTheme(e.target.dataset.t);
      addEventListener("keydown", (e) => {
        if (e.key === "ArrowRight" || e.key === "ArrowDown") {
          e.preventDefault();
            show(cur + 1);
        } else if (e.key === "ArrowLeft" || e.key === "ArrowUp") {
          e.preventDefault();
            show(cur - 1);
        } else if (e.key === "l") setLang(lang === "en" ? "es" : "en");
        else if (e.key === "t")
          setTheme(
            document.documentElement.dataset.theme === "dark"
              ? "light"
              : "dark",
          );
      });
      addEventListener("resize", fit);
      cur = Math.min(
        Math.max(+location.hash.slice(1) || 0, 0),
        frames.length - 1,
      );
      setLang("es");
